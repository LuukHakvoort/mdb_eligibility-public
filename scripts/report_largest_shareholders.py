"""Write the codebook's "largest shareholder per bank, and whether it
changes" deliverable, from data/extracted/unga_bank_year_reference_points
.csv (scripts/build_unga_iv.py).

Two outputs, both to `../Final dataset/codebook/` (not git-tracked, sibling
to this repo):

- `largest_shareholders_by_bank.csv` -- long format, one row per (bank,
  year): `bank, year, largest_shareholder_iso3, weight_pct, weight_basis`.
- `largest_shareholders_summary.md` -- one entry per bank, collapsing
  consecutive years with the same largest shareholder (or the same "no
  data" gap) into a single run, and explicitly stating whether that bank's
  largest shareholder ever changes within the panel.

Usage:  python3 scripts/report_largest_shareholders.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _panel import EXTRACTED_DIR, REPO  # noqa: E402

REFERENCE_CSV = EXTRACTED_DIR / "unga_bank_year_reference_points.csv"
FINAL_DATASET_REPO = REPO.parent / "Final dataset"
CODEBOOK_DIR = FINAL_DATASET_REPO / "codebook"
CSV_OUTPUT = CODEBOOK_DIR / "largest_shareholders_by_bank.csv"
MD_OUTPUT = CODEBOOK_DIR / "largest_shareholders_summary.md"

NO_DATA = "— (no data)"


def _runs(rows: list[dict]) -> list[tuple[str, int, int]]:
    """Collapse a bank's (year, shareholder-or-None) rows, sorted by year,
    into (label, start_year, end_year) runs of consecutive years sharing the
    same shareholder (or the same "no data" gap)."""

    runs: list[tuple[str, int, int]] = []
    for row in rows:
        label = row["largest_shareholder_iso3"] or NO_DATA
        year = row["year"]
        if runs and runs[-1][0] == label and runs[-1][2] == year - 1:
            runs[-1] = (label, runs[-1][1], year)
        else:
            runs.append((label, year, year))
    return runs


def summarize(reference: pd.DataFrame) -> tuple[list[dict], str]:
    csv_rows: list[dict] = []
    md_lines: list[str] = ["# Largest shareholder per bank\n",
                            "One entry per bank: the largest shareholder (by decision-making weight, "
                            "`scripts/build_shareholder_weights.py`) in each year, and whether it ever "
                            "changes within the panel. Generated by `scripts/report_largest_shareholders.py` "
                            "from `data/extracted/unga_bank_year_reference_points.csv` -- see "
                            "`codebook.md` for the full weight/renormalization/carry-forward rules.\n"]

    for bank, group in reference.sort_values(["bank", "year"]).groupby("bank"):
        rows = group[["year", "largest_shareholder_iso3", "largest_shareholder_weight_pct",
                       "largest_shareholder_weight_basis"]].to_dict("records")
        for r in rows:
            csv_rows.append({
                "bank": bank, "year": r["year"],
                "largest_shareholder_iso3": r["largest_shareholder_iso3"] if pd.notna(r["largest_shareholder_iso3"]) else "",
                "weight_pct": r["largest_shareholder_weight_pct"] if pd.notna(r["largest_shareholder_weight_pct"]) else "",
                "weight_basis": r["largest_shareholder_weight_basis"] if pd.notna(r["largest_shareholder_weight_basis"]) else "",
            })

        clean_rows = [{"year": r["year"],
                        "largest_shareholder_iso3": r["largest_shareholder_iso3"] if pd.notna(r["largest_shareholder_iso3"]) else None}
                       for r in rows]
        runs = _runs(clean_rows)
        distinct_shareholders = {label for label, _, _ in runs if label != NO_DATA}
        changes = len(distinct_shareholders) > 1

        run_text = ", ".join(
            f"{label} {start}" if start == end else f"{label} {start}-{end}"
            for label, start, end in runs
        )
        verdict = "changes" if changes else ("unchanged" if distinct_shareholders else "no data")
        md_lines.append(f"- **{bank}** ({verdict}): {run_text}")

    return csv_rows, "\n".join(md_lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--reference", type=Path, default=REFERENCE_CSV)
    parser.add_argument("--csv-output", type=Path, default=CSV_OUTPUT)
    parser.add_argument("--md-output", type=Path, default=MD_OUTPUT)
    args = parser.parse_args(argv)

    if not args.reference.is_file():
        print(f"error: {args.reference} does not exist. Run: python3 scripts/build_unga_iv.py", file=sys.stderr)
        return 2

    reference = pd.read_csv(args.reference)
    csv_rows, md_text = summarize(reference)

    args.csv_output.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(csv_rows, columns=["bank", "year", "largest_shareholder_iso3", "weight_pct", "weight_basis"]) \
        .to_csv(args.csv_output, index=False)
    args.md_output.parent.mkdir(parents=True, exist_ok=True)
    args.md_output.write_text(md_text, encoding="utf-8")

    print(f"{len(csv_rows)} (bank, year) rows -> {args.csv_output}")
    print(f"-> {args.md_output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
